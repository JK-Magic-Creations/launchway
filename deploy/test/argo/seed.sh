#!/usr/bin/env bash
# (Re)creates the test repository gitops.git from fixtures/, pushes it, applies
# the Argo CD Applications, syncs the ones without automated sync, and waits
# until all of them are Synced and Healthy on the new commit.
#
#   deploy/test/argo/seed.sh [--context kind-NAME] <host-git-url>
#
# <host-git-url> is the repository URL as seen from this machine, for example
# the one printed by git-url.sh: http://127.0.0.1:PORT/lwtest/gitops.git
#
# Recreating the repository resets history: every Application goes back to the
# first good version (busybox 1.36.1, MODE serve, verdict pass). Sync windows
# on the AppProject are removed.
# shellcheck source=lib.sh
source "$(dirname "$0")/lib.sh"
parse_context "$@"
set -- "${REST_ARGS[@]}"
require_kind_context
if [ $# -ne 1 ]; then
	echo "usage: $0 [--context kind-NAME] <host-git-url>" >&2
	exit 2
fi
URL=$1
case "$URL" in
http://127.0.0.1:* | http://localhost:*) ;;
*) echo "refusing $URL: expected a port-forwarded URL on 127.0.0.1 (see git-url.sh)" >&2; exit 2 ;;
esac
BASE=${URL%/"$GIT_REPO_PATH"}
AUTH=$(basic_auth_header)

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
cp -r "$ARGO_DIR/fixtures/." "$WORK/"
# apps/manual is a copy of apps/demo (Application demo-manual).
mkdir -p "$WORK/apps/manual"
cp "$ARGO_DIR/fixtures/apps/demo/"*.yaml "$WORK/apps/manual/"
cat >"$WORK/README.md" <<'EOF'
Test repository for Launchway's Argo CD integration tests. Generated by
deploy/test/argo/seed.sh; every run recreates it.
EOF

git -C "$WORK" init -q -b main
git -C "$WORK" add -A
git -C "$WORK" -c user.name="Launchway test" -c user.email=test@example.invalid commit -q -m "seed test fixtures"
SHA=$(git -C "$WORK" rev-parse HEAD)

log "recreating $URL"
code=$(curl -s -o /dev/null -w '%{http_code}' -X DELETE -H "$AUTH" "$BASE/api/v1/repos/${GIT_REPO_PATH%.git}")
case "$code" in 204 | 404) ;; *) echo "deleting the old repository failed: HTTP $code" >&2; exit 1 ;; esac
git -C "$WORK" -c http.extraHeader="$AUTH" push -q "$URL" main

# A push webhook to Argo CD, as a real Git server would have. Argo CD v3.3.7
# does not re-read Git for an Application whose resources are idle (see
# README), so without it a pushed commit is only noticed after a refresh
# annotation. LAUNCHWAY_TEST_ARGO_WEBHOOK=0 leaves it out, to test that path.
if [ "${LAUNCHWAY_TEST_ARGO_WEBHOOK:-1}" = 1 ]; then
	code=$(curl -s -o /dev/null -w '%{http_code}' -X POST -H "$AUTH" -H 'Content-Type: application/json' \
		"$BASE/api/v1/repos/${GIT_REPO_PATH%.git}/hooks" \
		-d '{"type":"gitea","active":true,"events":["push"],"config":{"url":"https://argocd-server.argocd.svc/api/webhook","content_type":"json"}}')
	[ "$code" = 201 ] || { echo "creating the webhook failed: HTTP $code" >&2; exit 1; }
fi

log "applying the AppProject (no sync windows) and the Applications"
K apply -f "$ARGO_DIR/argocd/project.yaml" >/dev/null
K -n argocd patch appproject lw-test --type merge -p '{"spec":{"syncWindows":null}}' >/dev/null
K apply -f "$ARGO_DIR/argocd/applications.yaml" >/dev/null

# Ask every Application to look at Git now instead of at the next poll.
for app in demo demo-manual plain demo-multi demo-wref; do
	K -n argocd annotate application "$app" argocd.argoproj.io/refresh=normal --overwrite >/dev/null
done

# Applications without automated sync: request a sync of the new commit once
# Argo CD has seen it. A running operation (left by a test) is waited out.
for app in demo-manual demo-multi; do
	deadline=$((SECONDS + 120))
	until [ "$(K -n argocd get application "$app" -o jsonpath='{.status.operationState.phase}')" != Running ] || [ $SECONDS -ge $deadline ]; do sleep 2; done
	until K -n argocd get application "$app" -o json | jq -e --arg sha "$SHA" '.status.sync.revision == $sha or ((.status.sync.revisions // []) | index($sha))' >/dev/null || [ $SECONDS -ge $deadline ]; do sleep 2; done
	request_sync "$app"
done

log "waiting for the Applications on $SHA"
wait_apps --sha "$SHA" demo demo-manual plain demo-multi demo-wref
log "seeded $SHA"
