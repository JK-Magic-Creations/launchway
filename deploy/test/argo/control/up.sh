#!/usr/bin/env bash
# Adds the control tests' objects to the kind cluster of deploy/test/argo (run its up.sh
# first) and (re)creates their repository, control.git, from fixtures/: Application
# ctl-canary then runs busybox 1.36.1, Healthy. Touches only names of its own (see
# cluster.yaml).
#
#   deploy/test/argo/control/up.sh [--context kind-NAME] <host-git-base-url>
#
# <host-git-base-url> is the port-forwarded Git server, for example http://127.0.0.1:PORT
source "$(dirname "$0")/../lib.sh"
parse_context "$@"
set -- "${REST_ARGS[@]}"
require_kind_context
if [ $# -ne 1 ]; then
	echo "usage: $0 [--context kind-NAME] <host-git-base-url>" >&2
	exit 2
fi
BASE=${1%/}
case "$BASE" in
http://127.0.0.1:* | http://localhost:*) ;;
*) echo "refusing $BASE: expected a port-forwarded URL on 127.0.0.1" >&2; exit 2 ;;
esac
CTL_DIR=$(cd "$(dirname "$0")" && pwd)

# settle_ctl SHA waits until ctl-canary is Synced and Healthy on SHA. The seed may start a
# canary (when an earlier run left another version stable): it is promoted fully, and an
# aborted rollout is retried, as a person (the kind admin) would.
settle_ctl() {
	local deadline=$((SECONDS + 300)) st
	while :; do
		st=$(K -n lw-ctl get rollout ctl -o jsonpath='{.status.phase}/{.status.abort}' 2>/dev/null || true)
		case "$st" in
		Paused/*) K -n lw-ctl patch rollout ctl --subresource=status --type=merge -p '{"status":{"promoteFull":true}}' >/dev/null ;;
		Degraded/true) K -n lw-ctl patch rollout ctl --subresource=status --type=merge -p '{"status":{"abort":false}}' >/dev/null ;;
		esac
		if WAIT_TIMEOUT=4 wait_apps --sha "$1" ctl-canary 2>/dev/null; then return 0; fi
		if [ $SECONDS -ge $deadline ]; then
			echo "ctl-canary did not settle (rollout $st)" >&2
			return 1
		fi
		sleep 2
	done
}
REPO=${GIT_USER}/control
AUTH=$(basic_auth_header)

log "applying the control tests' namespace, AppProject, repository secret, Application and RBAC"
K apply -f "$CTL_DIR/cluster.yaml" >/dev/null

# The chart's admission policy for rollout status patches, rendered from the chart itself
# and pointed at this cluster's deploy runner identity, so the policy under test is the
# one the chart ships.
log "applying the chart's rollout status admission policy for argocd/lw-deployer"
helm template lw "$CTL_DIR/../../../helm/launchway" --namespace argocd \
	--set postgresql.enabled=true \
	--set 'delivery.environments[0].name=kind' --set 'delivery.environments[0].target=kind' \
	--set 'delivery.environments[0].projects[0]=shop' \
	--set delivery.deployRunner.enabled=true --set delivery.deployRunner.target=kind \
	--set 'delivery.deployRunner.applications[0].projects[0]=shop' --set 'delivery.deployRunner.applications[0].names[0]=ctl-canary' \
	--set 'delivery.deployRunner.rolloutNamespaces[0]=lw-ctl' --set 'delivery.deployRunner.rbac.controlRollouts.lw-ctl[0]=ctl' \
	--set 'delivery.deployRunner.repos.control.url=http://example.invalid/control.git' \
	--show-only templates/deploy-runner-control.yaml |
	sed -e 's/system:serviceaccount:argocd:lw-launchway-deploy-runner/system:serviceaccount:argocd:lw-deployer/' \
		-e 's/name: lw-launchway-deploy-runner-rollouts-argocd/name: lw-ctl-deployer-rollouts/' \
		-e 's/policyName: lw-launchway-deploy-runner-rollouts-argocd/policyName: lw-ctl-deployer-rollouts/' |
	K apply -f - >/dev/null
K get validatingadmissionpolicy lw-ctl-deployer-rollouts -o jsonpath='{.spec.matchConditions[0].expression}' | grep -q lw-deployer ||
	{ echo "the rendered policy does not name lw-deployer" >&2; exit 1; }

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
cp -r "$CTL_DIR/fixtures/." "$WORK/"
echo "Test repository for Launchway's control tests. Generated by deploy/test/argo/control/up.sh." >"$WORK/README.md"
git -C "$WORK" init -q -b main
git -C "$WORK" add -A
git -C "$WORK" -c user.name="Launchway test" -c user.email=test@example.invalid commit -q -m "seed control fixtures"
SHA=$(git -C "$WORK" rev-parse HEAD)

log "recreating $BASE/$REPO.git"
code=$(curl -s -o /dev/null -w '%{http_code}' -X DELETE -H "$AUTH" "$BASE/api/v1/repos/$REPO")
case "$code" in 204 | 404) ;; *) echo "deleting the old repository failed: HTTP $code" >&2; exit 1 ;; esac
git -C "$WORK" -c http.extraHeader="$AUTH" push -q "$BASE/$REPO.git" main
code=$(curl -s -o /dev/null -w '%{http_code}' -X POST -H "$AUTH" -H 'Content-Type: application/json' "$BASE/api/v1/repos/$REPO/hooks" \
	-d '{"type":"gitea","active":true,"events":["push"],"config":{"url":"https://argocd-server.argocd.svc/api/webhook","content_type":"json"}}')
[ "$code" = 201 ] || { echo "creating the webhook failed: HTTP $code" >&2; exit 1; }

K -n argocd annotate application ctl-canary argocd.argoproj.io/refresh=normal --overwrite >/dev/null
log "waiting for ctl-canary on $SHA"
settle_ctl "$SHA"
log "control seeded at $SHA"
