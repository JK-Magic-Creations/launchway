package importer

import (
	"fmt"
	"strings"
)

// GuideMarkers delimit the generated part of docs/guide/move-your-pipelines.md.
const (
	GuideStart = "<!-- importer-tables:start (generated by internal/importer: go test ./internal/importer -run TestGuide -update-docs) -->"
	GuideEnd   = "<!-- importer-tables:end -->"
)

var classHeading = map[Class]string{
	Exact:     "Converts exactly",
	Different: "Converts with a difference",
	Manual:    "Needs a person",
}

func cell(s string) string {
	s = strings.ReplaceAll(strings.ReplaceAll(s, "|", "/"), "\n", " ")
	// Text outside code spans must not hold a tag or a template brace: the page is compiled as a template.
	parts := strings.Split(s, "`")
	for i := 0; i < len(parts); i += 2 {
		parts[i] = strings.NewReplacer("<", "&lt;", ">", "&gt;", "{{", "&#123;&#123;", "}}", "&#125;&#125;").Replace(parts[i])
	}
	return strings.Join(parts, "`")
}

// GuideTables writes the tables of the guide from the readers' own
// classification tables, so the page cannot say anything the readers do not do.
func GuideTables() string {
	var b strings.Builder
	b.WriteString(GuideStart + "\n\n")
	for _, f := range formats {
		fmt.Fprintf(&b, "## %s\n\n", f.Title)
		fmt.Fprintf(&b, "Where it lives: %s. Import it with `launchway import pipeline --from %s`.\n\n", cell(f.Where), f.ID)
		n := map[Class]int{}
		for _, c := range f.Table {
			n[c.Class]++
		}
		fmt.Fprintf(&b, "%d constructs are known: %d convert exactly, %d convert with a difference, %d need a person.\n\n", len(f.Table), n[Exact], n[Different], n[Manual])
		for _, cl := range []Class{Exact, Different, Manual} {
			var rows []Construct
			for _, c := range f.Table {
				if c.Class == cl {
					rows = append(rows, c)
				}
			}
			if len(rows) == 0 {
				continue
			}
			fmt.Fprintf(&b, "### %s: %s\n\n", f.Title, classHeading[cl])
			b.WriteString("| In the old file | What the importer does | What you do |\n|---|---|---|\n")
			for _, c := range rows {
				next := c.Next
				if next == "" {
					next = "Nothing."
				}
				fmt.Fprintf(&b, "| %s | %s | %s |\n", cell(c.Name), cell(c.Plain()), cell(next))
			}
			b.WriteString("\n")
		}
	}
	b.WriteString("## What every import adds\n\n")
	b.WriteString("These notes come from the writer that makes the Launchway file, whatever the source format.\n\n")
	b.WriteString("| Situation | What the importer does | What you do |\n|---|---|---|\n")
	for _, c := range writerTable {
		next := c.Next
		if next == "" {
			next = "Nothing."
		}
		fmt.Fprintf(&b, "| %s | %s | %s |\n", cell(c.Name), cell(c.Plain()), cell(next))
	}
	b.WriteString("\n" + GuideEnd + "\n")
	return b.String()
}
