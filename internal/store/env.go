package store

import (
	"database/sql"
	"errors"
	"strconv"
	"strings"
)

// Row is what a single-row query returns.
type Row interface {
	Scan(dest ...any) error
}

// Querier runs statements written with ? (they are rebound for PostgreSQL by
// the implementation).
type Querier interface {
	Exec(q string, args ...any) (sql.Result, error)
	Query(q string, args ...any) (*sql.Rows, error)
	QueryRow(q string, args ...any) Row
}

// Tx is a transaction.
type Tx interface {
	Querier
	Commit() error
	Rollback() error
}

// Conn is a database connection pool that can begin transactions.
type Conn interface {
	Querier
	Begin() (Tx, error)
}

// Env is what the store needs from its host: the connection, which database
// it is, and (SQLite only) the process-wide write lock.
type Env struct {
	DB Conn
	PG bool
	// WriteLock takes the SQLite write lock and returns its release; nil or a
	// no-op on PostgreSQL.
	WriteLock func() func()
}

func (e *Env) lock() func() {
	if e.PG || e.WriteLock == nil {
		return func() {}
	}
	return e.WriteLock()
}

// Q is the handle a store method gets inside Do. It is a Querier whose scope
// is fixed; BaseArg is the value every Base statement binds to base_id.
type Q struct {
	Querier
	scope Scope
	pg    bool
}

// Base is the argument for a statement's base_id.
func (q *Q) Base() string { return string(q.scope.id) }

// Do runs fn in the scope. A write runs in one transaction under the SQLite
// write lock; on PostgreSQL every scoped call, read or write, is one
// transaction that begins by setting app.base_id for that transaction only,
// so a pooled connection carries nothing over. A SQLite read needs no
// transaction (the wall there is the predicate and the architecture test).
func (e *Env) Do(sc Scope, write bool, fn func(q *Q) error) error {
	if !sc.Valid() {
		return ErrNotFound
	}
	if !write && !e.PG {
		return fn(&Q{Querier: e.DB, scope: sc})
	}
	if write {
		defer e.lock()()
	}
	tx, err := e.DB.Begin()
	if err != nil {
		return err
	}
	defer func() { _ = tx.Rollback() }()
	if e.PG {
		if _, err := tx.Exec(`SELECT set_config('app.base_id', ?, true)`, string(sc.id)); err != nil {
			return err
		}
	}
	if err := fn(&Q{Querier: tx, scope: sc, pg: e.PG}); err != nil {
		return err
	}
	return tx.Commit()
}

// doGlobal runs fn on the tables that belong to no Base (the Bases
// themselves, accounts, the setup code).
func (e *Env) doGlobal(write bool, fn func(q Querier) error) error {
	if !write {
		return fn(e.DB)
	}
	defer e.lock()()
	tx, err := e.DB.Begin()
	if err != nil {
		return err
	}
	defer func() { _ = tx.Rollback() }()
	if err := fn(tx); err != nil {
		return err
	}
	return tx.Commit()
}

// Rebind turns ? placeholders into $1, $2 ... for PostgreSQL.
func Rebind(pg bool, q string) string {
	if !pg || !strings.Contains(q, "?") {
		return q
	}
	var b strings.Builder
	n := 0
	for _, r := range q {
		if r == '?' {
			n++
			b.WriteString("$" + strconv.Itoa(n))
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}

// Render fills in the few types that differ between the two databases.
func Render(pg bool, m string) string {
	if pg {
		return strings.NewReplacer(
			"{{ID}}", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
			"{{BIG}}", "BIGINT",
			"{{BYTES}}", "BYTEA",
			"{{RAND}}", "md5(random()::text || clock_timestamp()::text)",
			"{{INSTR}}", "strpos",
		).Replace(m)
	}
	return strings.NewReplacer(
		"{{ID}}", "INTEGER PRIMARY KEY AUTOINCREMENT",
		"{{BIG}}", "INTEGER",
		"{{BYTES}}", "BLOB",
		"{{RAND}}", "lower(hex(randomblob(16)))",
		"{{INSTR}}", "instr",
	).Replace(m)
}

// SQLConn adapts a *sql.DB to Conn, rebinding placeholders. The engine has
// its own adapter (with retry through a database failover); this one is for
// tests, the console commands and a second connection under another role.
type SQLConn struct {
	DB *sql.DB
	PG bool
}

type sqlRow struct{ *sql.Row }

func (c SQLConn) Exec(q string, a ...any) (sql.Result, error) {
	return c.DB.Exec(Rebind(c.PG, q), a...) //nolint:noctx // the store passes no context to statements yet
}
func (c SQLConn) Query(q string, a ...any) (*sql.Rows, error) {
	return c.DB.Query(Rebind(c.PG, q), a...) //nolint:noctx // as above
}
func (c SQLConn) QueryRow(q string, a ...any) Row {
	return sqlRow{c.DB.QueryRow(Rebind(c.PG, q), a...)} //nolint:noctx // as above
}
func (c SQLConn) Begin() (Tx, error) {
	tx, err := c.DB.Begin() //nolint:noctx // as above
	if err != nil {
		return nil, err
	}
	return sqlTx{tx, c.PG}, nil
}

type sqlTx struct {
	*sql.Tx
	pg bool
}

func (t sqlTx) Exec(q string, a ...any) (sql.Result, error) {
	return t.Tx.Exec(Rebind(t.pg, q), a...) //nolint:noctx // as above
}
func (t sqlTx) Query(q string, a ...any) (*sql.Rows, error) {
	return t.Tx.Query(Rebind(t.pg, q), a...) //nolint:noctx // as above
}
func (t sqlTx) QueryRow(q string, a ...any) Row {
	return sqlRow{t.Tx.QueryRow(Rebind(t.pg, q), a...)} //nolint:noctx // as above
}

func isNoRows(err error) bool { return errors.Is(err, sql.ErrNoRows) }
