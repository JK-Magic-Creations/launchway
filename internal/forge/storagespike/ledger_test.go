// Ledger is the database side of both candidates: for B the refs, the pack
// manifest and the generation; for A the audit ledger of ref updates.
type Ledger struct {
	db    *sql.DB
	PG    bool
	Fault Fault
	// dropAfter makes the next Commit report a lost connection after the
	// database committed (a failover in the middle of the answer).
}

// ErrStale means a compare-and-swap failed: the ref is not where the pusher
// believed. Nothing was changed.
type ErrStale struct {
	Ref, Have, Want string
}

func (e *ErrStale) Error() string {
	return fmt.Sprintf("the branch moved: %s is at %s, not at %s", e.Ref, short(e.Have), short(e.Want))
}

func short(s string) string {
	if len(s) > 10 {
		return s[:10]
	}
	if s == "" {
		return "(nothing)"
	}
	return s
}

// OpenLedger opens SQLite at a path, or PostgreSQL at a URL.
func OpenLedger(addr string) (*Ledger, error) {
	if strings.HasPrefix(addr, "postgres://") || strings.HasPrefix(addr, "postgresql://") {
		db, err := sql.Open("pgx", addr)
		if err != nil {
			return nil, err
		}
		db.SetMaxOpenConns(8)
		return &Ledger{db: db, PG: true}, nil
	}
	q := url.Values{}
	for _, p := range []string{"busy_timeout(30000)", "journal_mode(WAL)", "synchronous(NORMAL)"} {
		q.Add("_pragma", p)
	}
	q.Set("_txlock", "immediate")
	db, err := sql.Open("sqlite", "file:"+addr+"?"+q.Encode())
	if err != nil {
		return nil, err
	}
	db.SetMaxOpenConns(4)
	return &Ledger{db: db}, nil
}

// Close closes the connection pool.
func (l *Ledger) Close() error { return l.db.Close() }

// DB is the underlying handle (the blob store shares it).
func (l *Ledger) DB() *sql.DB { return l.db }

func (l *Ledger) q(s string) string {
	if !l.PG {
		return s
	}
	var b strings.Builder
	n := 0
	for _, r := range s {
		if r == '?' {
			n++
			fmt.Fprintf(&b, "$%d", n)
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}

const schema = `
CREATE TABLE IF NOT EXISTS spike_refs (
  repo_id TEXT NOT NULL, name TEXT NOT NULL, target TEXT NOT NULL, updated_gen BIGINT NOT NULL,
  PRIMARY KEY (repo_id, name));
CREATE TABLE IF NOT EXISTS spike_generation (repo_id TEXT PRIMARY KEY, gen BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS spike_packs (
  repo_id TEXT NOT NULL, pack_id TEXT NOT NULL, blob_key TEXT NOT NULL, bytes BIGINT NOT NULL,
  state TEXT NOT NULL, born_gen BIGINT NOT NULL DEFAULT 0, died_gen BIGINT NOT NULL DEFAULT 0,
  created_ms BIGINT NOT NULL, retired_ms BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY (repo_id, pack_id));
CREATE TABLE IF NOT EXISTS spike_maintenance (repo_id TEXT PRIMARY KEY, holder TEXT NOT NULL, until_ms BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS spike_meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS spike_ledger (
  seq INTEGER PRIMARY KEY AUTOINCREMENT, repo_id TEXT NOT NULL, ref TEXT NOT NULL, old TEXT NOT NULL, new TEXT NOT NULL, at_ms BIGINT NOT NULL);
`

// Init creates the tables.
func (l *Ledger) Init(ctx context.Context) error {
	s := schema
	if l.PG {
		s = strings.Replace(s, "INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", 1)
	}
	for _, stmt := range strings.Split(s, ";\n") {
		if strings.TrimSpace(stmt) == "" {
			continue
		}
		if _, err := l.db.ExecContext(ctx, stmt); err != nil {
			return fmt.Errorf("creating the spike tables: %w", err)
		}
	}
	return nil
}

// Marker returns the store marker the database holds, creating it with id if
// there is none. The same identifier is written into the blob store, and a
// server whose blob store does not carry it refuses to host: it is the
// discipline of the artifact store marker, so two servers that were given
// different stores cannot silently split the repositories.
func (l *Ledger) Marker(ctx context.Context, id string) (string, error) {
	if _, err := l.db.ExecContext(ctx, l.q(`INSERT INTO spike_meta(key, value) VALUES('repo_store_marker', ?) ON CONFLICT(key) DO NOTHING`), id); err != nil {
		return "", err
	}
	var got string
	err := l.db.QueryRowContext(ctx, l.q(`SELECT value FROM spike_meta WHERE key = 'repo_store_marker'`)).Scan(&got)
	return got, err
}

// EnsureRepo makes a repository exist (generation 0, no refs).
func (l *Ledger) EnsureRepo(ctx context.Context, repo string) error {
	_, err := l.db.ExecContext(ctx, l.q(`INSERT INTO spike_generation(repo_id, gen) VALUES(?, 0) ON CONFLICT(repo_id) DO NOTHING`), repo)
	return err
}

// PackInfo is one row of the manifest.
type PackInfo struct {
	ID      string // SHA-256 of the pack file
	BlobKey string
	Bytes   int64
	State   string // pending, live, retired, orphan
	Born    int64
	Died    int64
}

func nowMS() int64 { return time.Now().UnixMilli() }

// RegisterPack records an uploaded pack as pending. Registering the same
// pack again (a retry) changes nothing.
func (l *Ledger) RegisterPack(ctx context.Context, repo string, p PackInfo) error {
	_, err := l.db.ExecContext(ctx, l.q(`INSERT INTO spike_packs(repo_id, pack_id, blob_key, bytes, state, created_ms)
		VALUES(?, ?, ?, ?, 'pending', ?) ON CONFLICT(repo_id, pack_id) DO NOTHING`), repo, p.ID, p.BlobKey, p.Bytes, nowMS())
	return err
}

// RefUpdate is one line of a push: Old and New are full IDs, all zeros (or
// empty) meaning none.
type RefUpdate struct{ Name, Old, New string }

func isZero(s string) bool { return strings.Trim(s, "0") == "" }

func norm(s string) string {
	if isZero(s) {
		return ""
	}
	return s
}

// Commit is the commit point of a push: in one transaction it compares and
// swaps every ref, makes the pack live and bumps the generation. A ref that is
// not where the pusher said it was refuses the whole batch with ErrStale and
// changes nothing. It returns the new generation.
func (l *Ledger) Commit(ctx context.Context, repo string, ups []RefUpdate, pack string) (int64, error) {
	tx, err := l.db.BeginTx(ctx, nil)
	if err != nil {
		return 0, err
	}
	defer tx.Rollback()
	f := l.Fault
	lock := ""
	if l.PG {
		lock = " FOR UPDATE" // one push at a time per repository: the generation row is the lock
	}
	var gen int64
	if err := tx.QueryRowContext(ctx, l.q(`SELECT gen FROM spike_generation WHERE repo_id = ?`+lock), repo).Scan(&gen); err != nil {
		return 0, fmt.Errorf("reading the generation: %w", err)
	}
	for _, u := range ups {
		var cur string
		err := tx.QueryRowContext(ctx, l.q(`SELECT target FROM spike_refs WHERE repo_id = ? AND name = ?`), repo, u.Name).Scan(&cur)
		if err != nil && !errors.Is(err, sql.ErrNoRows) {
			return 0, err
		}
		if cur != norm(u.Old) {
			return 0, &ErrStale{Ref: u.Name, Have: cur, Want: norm(u.Old)}
		}
	}
	if err := f.Hit(PtTxAfterCheck); err != nil {
		return 0, err
	}
	for _, u := range ups {
		if isZero(u.New) {
			_, err = tx.ExecContext(ctx, l.q(`DELETE FROM spike_refs WHERE repo_id = ? AND name = ?`), repo, u.Name)
		} else {
			_, err = tx.ExecContext(ctx, l.q(`INSERT INTO spike_refs(repo_id, name, target, updated_gen) VALUES(?, ?, ?, ?)
				ON CONFLICT(repo_id, name) DO UPDATE SET target = excluded.target, updated_gen = excluded.updated_gen`), repo, u.Name, u.New, gen+1)
		}
		if err != nil {
			return 0, err
		}
	}
	if err := f.Hit(PtTxAfterRefs); err != nil {
		return 0, err
	}
	if pack != "" {
		res, err := tx.ExecContext(ctx, l.q(`UPDATE spike_packs SET state = 'live', born_gen = ? WHERE repo_id = ? AND pack_id = ? AND state IN ('pending', 'live')`), gen+1, repo, pack)
		if err != nil {
			return 0, err
		}
		if n, _ := res.RowsAffected(); n != 1 {
			return 0, fmt.Errorf("the pack %s is not registered; refusing to move refs to objects nobody can fetch", short(pack))
		}
	}
	if err := f.Hit(PtTxAfterPack); err != nil {
		return 0, err
	}
	if _, err := tx.ExecContext(ctx, l.q(`UPDATE spike_generation SET gen = ? WHERE repo_id = ?`), gen+1, repo); err != nil {
		return 0, err
	}
	if err := f.Hit(PtTxBeforeCommit); err != nil {
		return 0, err
	}
	switch {
	case f.Is("db", "dropbefore"):
		return 0, fmt.Errorf("%w: connection lost before the commit", ErrInjected)
	}
	if err := tx.Commit(); err != nil {
		return 0, err
	}
	if f.Is("db", "dropafter") {
		return 0, fmt.Errorf("%w: connection lost after the commit (the answer never arrived)", ErrInjected)
	}
	if err := f.Hit(PtTxAfterCommit); err != nil {
		return gen + 1, err
	}
	return gen + 1, nil
}

// Snapshot is a consistent reading of a repository: generation, refs and the
// live packs, taken in one transaction.
type Snapshot struct {
	Gen   int64
	Refs  map[string]string
	Packs []PackInfo // live, oldest first
}

// Snapshot reads the repository's state.
func (l *Ledger) Snapshot(ctx context.Context, repo string) (Snapshot, error) {
	s := Snapshot{Refs: map[string]string{}}
	opts := &sql.TxOptions{ReadOnly: true}
	if l.PG {
		opts.Isolation = sql.LevelRepeatableRead
	}
	tx, err := l.db.BeginTx(ctx, opts)
	if err != nil {
		return s, err
	}
	defer tx.Rollback()
	if err := tx.QueryRowContext(ctx, l.q(`SELECT gen FROM spike_generation WHERE repo_id = ?`), repo).Scan(&s.Gen); err != nil {
		return s, fmt.Errorf("reading the generation: %w", err)
	}
	readRefs := func() error {
		rows, err := tx.QueryContext(ctx, l.q(`SELECT name, target FROM spike_refs WHERE repo_id = ?`), repo)
		if err != nil {
			return err
		}
		defer rows.Close()
		for rows.Next() {
			var n, t string
			if err := rows.Scan(&n, &t); err != nil {
				return err
			}
			s.Refs[n] = t
		}
		return rows.Err()
	}
	if err := readRefs(); err != nil {
		return s, err
	}
	prows, err := tx.QueryContext(ctx, l.q(`SELECT pack_id, blob_key, bytes, state, born_gen, died_gen FROM spike_packs WHERE repo_id = ? AND state = 'live' ORDER BY born_gen, pack_id`), repo)
	if err != nil {
		return s, err
	}
	defer prows.Close()
	for prows.Next() {
		var p PackInfo
		if err := prows.Scan(&p.ID, &p.BlobKey, &p.Bytes, &p.State, &p.Born, &p.Died); err != nil {
			return s, err
		}
		s.Packs = append(s.Packs, p)
	}
	return s, prows.Err()
}

// Retire consolidates: it adds the new pack as live (born at the new
// generation) and retires every live pack born at or before snapshotGen, in
// one transaction, bumping the generation so caches notice. Packs that
// arrived after the snapshot stay live. It refuses when nothing is left to
// retire against (the snapshot is out of date and the consolidated pack may
// not hold what it replaces: the caller starts again).
func (l *Ledger) Consolidate(ctx context.Context, repo string, snapshotGen int64, snapshotRefs map[string]string, np PackInfo) error {
	tx, err := l.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	lock := ""
	if l.PG {
		lock = " FOR UPDATE"
	}
	var gen int64
	if err := tx.QueryRowContext(ctx, l.q(`SELECT gen FROM spike_generation WHERE repo_id = ?`+lock), repo).Scan(&gen); err != nil {
		return err
	}
	// The consolidated pack holds everything reachable from the refs as of
	// snapshotGen. Packs born after it stay live, whatever happened since.
	now := nowMS()
	if _, err := tx.ExecContext(ctx, l.q(`UPDATE spike_packs SET state = 'retired', died_gen = ?, retired_ms = ? WHERE repo_id = ? AND state = 'live' AND born_gen <= ?`),
		gen+1, now, repo, snapshotGen); err != nil {
		return err
	}
	if _, err := tx.ExecContext(ctx, l.q(`INSERT INTO spike_packs(repo_id, pack_id, blob_key, bytes, state, born_gen, created_ms)
		VALUES(?, ?, ?, ?, 'live', ?, ?) ON CONFLICT(repo_id, pack_id) DO UPDATE SET state = 'live', born_gen = excluded.born_gen`),
		repo, np.ID, np.BlobKey, np.Bytes, gen+1, now); err != nil {
		return err
	}
	if _, err := tx.ExecContext(ctx, l.q(`UPDATE spike_generation SET gen = ? WHERE repo_id = ?`), gen+1, repo); err != nil {
		return err
	}
	return tx.Commit()
}

// Retired lists packs retired before the cut-off (Unix ms).
func (l *Ledger) Retired(ctx context.Context, repo string, beforeMS int64) ([]PackInfo, error) {
	rows, err := l.db.QueryContext(ctx, l.q(`SELECT pack_id, blob_key, bytes, state FROM spike_packs WHERE repo_id = ? AND state = 'retired' AND retired_ms <= ?`), repo, beforeMS)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []PackInfo
	for rows.Next() {
		var p PackInfo
		if err := rows.Scan(&p.ID, &p.BlobKey, &p.Bytes, &p.State); err != nil {
			return nil, err
		}
		out = append(out, p)
	}
	return out, rows.Err()
}

// MarkDeleted records that a retired pack's blob is gone.
func (l *Ledger) MarkDeleted(ctx context.Context, repo, pack string) error {
	_, err := l.db.ExecContext(ctx, l.q(`UPDATE spike_packs SET state = 'orphan' WHERE repo_id = ? AND pack_id = ? AND state = 'retired'`), repo, pack)
	return err
}

// Pending lists pending packs older than the cut-off: uploads whose push never
// committed.
func (l *Ledger) Pending(ctx context.Context, repo string, beforeMS int64) ([]PackInfo, error) {
	rows, err := l.db.QueryContext(ctx, l.q(`SELECT pack_id, blob_key, bytes, state FROM spike_packs WHERE repo_id = ? AND state = 'pending' AND created_ms <= ?`), repo, beforeMS)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []PackInfo
	for rows.Next() {
		var p PackInfo
		if err := rows.Scan(&p.ID, &p.BlobKey, &p.Bytes, &p.State); err != nil {
			return nil, err
		}
		out = append(out, p)
	}
	return out, rows.Err()
}

// SetPackState sets a pack's state (orphaning a pending pack).
func (l *Ledger) SetPackState(ctx context.Context, repo, pack, from, to string) error {
	_, err := l.db.ExecContext(ctx, l.q(`UPDATE spike_packs SET state = ? WHERE repo_id = ? AND pack_id = ? AND state = ?`), to, repo, pack, from)
	return err
}

// Lease takes the repository's maintenance lease for d, or reports that
// another holder has it.
func (l *Ledger) Lease(ctx context.Context, repo, holder string, d time.Duration) (bool, error) {
	now := nowMS()
	res, err := l.db.ExecContext(ctx, l.q(`INSERT INTO spike_maintenance(repo_id, holder, until_ms) VALUES(?, ?, ?)
		ON CONFLICT(repo_id) DO UPDATE SET holder = excluded.holder, until_ms = excluded.until_ms
		WHERE spike_maintenance.until_ms < ? OR spike_maintenance.holder = excluded.holder`), repo, holder, now+d.Milliseconds(), now)
	if err != nil {
		return false, err
	}
	n, _ := res.RowsAffected()
	return n > 0, nil
}

// AppendLedger records a ref update in the audit ledger (candidate A).
func (l *Ledger) AppendLedger(ctx context.Context, repo string, u RefUpdate) error {
	_, err := l.db.ExecContext(ctx, l.q(`INSERT INTO spike_ledger(repo_id, ref, old, new, at_ms) VALUES(?, ?, ?, ?, ?)`), repo, u.Name, norm(u.Old), norm(u.New), nowMS())
	return err
}

// LedgerRows lists the audit ledger of a repository, oldest first.
func (l *Ledger) LedgerRows(ctx context.Context, repo string) ([]RefUpdate, error) {
	rows, err := l.db.QueryContext(ctx, l.q(`SELECT ref, old, new FROM spike_ledger WHERE repo_id = ? ORDER BY seq`), repo)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []RefUpdate
	for rows.Next() {
		var u RefUpdate
		if err := rows.Scan(&u.Name, &u.Old, &u.New); err != nil {
			return nil, err
		}
		out = append(out, u)
	}
	return out, rows.Err()
}
